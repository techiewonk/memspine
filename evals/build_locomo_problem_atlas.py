# Hand-label validation (full-persp-loc has hand codes; the classifier is run on the same run and compared)
# ---------------------------------------------------------------------------------------------------------------------
def validate_vs_hand(ds: dict, errata: dict) -> dict:
    fx = OUT_DIR / "fx_full-persp-loc" / "per_question.jsonl"
    if not fx.exists() or not HAND_LABELS.exists():
        return {"available": False}
    rows = jl(fx)
    lab = {}
    for line in HAND_LABELS.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        c, q, s = line.split()
        lab[(c, q)] = s
    cl = classify_all([r for r in rows if r["category"] != "adversarial"], ds, errata, {})
    exact = grp = n = 0
    conf: collections.Counter = collections.Counter()
    for x in cl:
        r = x["row"]
        k = (r["item"], r["qid"])
        if r["correct"] or k not in lab:
            continue
        n += 1
        mine, hand = x["cls"]["stage"], lab[k]
        exact += mine == hand
        grp += mine.split(":")[0] == hand.split(":")[0]
        conf[(hand, mine)] += 1
    return {"available": True, "n": n, "exact": exact, "group": grp, "confusion": {f"{h}>{m}": v for (h, m), v in sorted(conf.items(), key=lambda kv: -kv[1])}}


