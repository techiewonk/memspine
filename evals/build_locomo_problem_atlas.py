    A("| **all wrong** | | | " + " | ".join(f"**{v}**" for v in cat_tot) + f" | **{wrong}** | 100 |")
    A("")
    A("| stage | single-hop | multi-hop | temporal | open-domain | total |")
    A("|---|---:|---:|---:|---:|---:|")
    for s in PC.STAGE_NAME:
        if s == "ok":
            continue
        cells = [counts["stage_cat"].get((s, cat), 0) for cat in CATS]
