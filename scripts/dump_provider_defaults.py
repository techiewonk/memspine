"""Generate the provider-owned defaults reference without constructing services."""

from __future__ import annotations

import argparse
import html
import json
from pathlib import Path
from typing import cast

from memspine.providers import provider_settings_reference
from memspine.providers.contracts import Category
from memspine.providers.registry import KIND_TO_CATEGORY, get_registry, provider_kinds

ROOT = Path(__file__).resolve().parents[1]


def code(value: str) -> str:
    return "<code>" + html.escape(value).replace("|", "&#124;") + "</code>"


def render() -> str:
    rows = [
        "# Provider-owned settings and defaults",
        "",
        "Generated by `scripts/dump_provider_defaults.py` from registered settings schemas.",
        "No model or service is constructed. Required values are intentionally not invented.",
        "Model-dependent dimensions are resolved by the selected settings validator; changing",
        "a model can require a new dimension or an explicit projection migration.",
        "Vector tables derive their dimensions from the embedder, rather than a conflicting DB default.",
        "For configuration paths and execution rules see [provider operations](PROVIDER_OPERATIONS.md).",
        "",
        "| Category | Provider | Defaults | Required fields |",
        "|---|---|---|---|",
    ]
    for kind in provider_kinds():
        category = cast(Category, KIND_TO_CATEGORY[kind])
        for name in get_registry(kind).names():
            reference = provider_settings_reference(category, name)
            defaults = (
                "<br>".join(
                    code(f"{key} = {json.dumps(value, ensure_ascii=False, sort_keys=True)}")
                    for key, value in reference["defaults"].items()
                )
                or "No native options"
            )
            required = ", ".join(code(key) for key in reference["required"]) or "None"
            rows.append(f"| {category} | {code(name)} | {defaults} | {required} |")
    rows.extend(
        [
            "",
            "Schema defaults do not include credentials or live Engine configuration. Nullable fields",
            "remain explicit: a null device delegates placement to the selected provider; an omitted",
            "required deadline is an error. FlashRank's null model uses its installed library default.",
            "Local LLM file paths and remote credentials must be supplied by the deployment.",
            "",
            "Inspect one provider, including validation constraints, without starting an Engine:",
            "",
            "```python",
            "from memspine.providers import provider_settings_reference",
            "print(provider_settings_reference('embedding', 'fastembed'))",
            "print(provider_settings_reference('llm', 'litellm'))",
            "```",
            "",
        ]
    )
    return "\n".join(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "PROVIDER_DEFAULTS.md")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not args.out.exists() or args.out.read_text(encoding="utf-8") != content:
            print(f"out of date: {args.out}")
            return 1
        print(f"up to date: {args.out}")
        return 0
    args.out.write_text(content, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
