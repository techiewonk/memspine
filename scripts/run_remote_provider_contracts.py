#!/usr/bin/env python3
"""Run real OpenSearch and Weaviate projection contracts in owned Docker containers.

Only two official, version-pinned images are used. Ports bind to loopback on
Docker-assigned ephemeral ports, containers use no host mounts, and cleanup only
removes container names generated by this invocation.
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import time
import uuid
from pathlib import Path
from typing import Any
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
LABEL = "memspine.remote-provider-contract=true"
IMAGES = {
    "opensearch": "opensearchproject/opensearch:2.19.5",
    "weaviate": "cr.weaviate.io/semitechnologies/weaviate:1.32.4",
}


def run(args: list[str], *, check: bool = True) -> str:
    result = subprocess.run(
        args,
        cwd=ROOT,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        check=False,
    )
    if check and result.returncode:
        raise RuntimeError(f"command failed ({result.returncode}): {args[0]}\n{result.stdout}")
    return result.stdout.strip()


def port(name: str, internal: int) -> int:
    output = run(["docker", "port", name, f"{internal}/tcp"])
    return int(output.splitlines()[0].rsplit(":", maxsplit=1)[1])


def wait_http(host_port: int, path: str, timeout_s: float) -> None:
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        try:
            with urlopen(f"http://127.0.0.1:{host_port}{path}", timeout=2):
                return
        except Exception:
            time.sleep(1)
    raise TimeoutError(f"provider did not become ready on loopback port {host_port}")


def start(
    service: str,
    image: str,
    suffix: str,
    exposed_ports: tuple[int, ...],
    env: dict[str, str],
    memory: str,
) -> str:
    name = f"memspine-remote-{suffix}-{service}"
    command = ["docker", "run", "--detach", "--name", name, "--label", LABEL, "--memory", memory]
    for internal_port in exposed_ports:
        command.extend(("--publish", f"127.0.0.1::{internal_port}"))
    for key, value in env.items():
        command.extend(("--env", f"{key}={value}"))
    command.append(image)
    run(command)
    return name


def redact(output: str, secrets_to_redact: list[str]) -> str:
    for secret in sorted((value for value in secrets_to_redact if value), key=len, reverse=True):
        output = output.replace(secret, "<redacted>")
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path)
    options = parser.parse_args()
    names: list[str] = []
    suffix = uuid.uuid4().hex[:12]
    evidence: dict[str, Any] = {
        "images": {},
        "services": {},
        "pytest_exit_code": None,
        "pytest_summary": None,
    }
    child_env = os.environ.copy()
    child_env.update(
        {
            "PYTHONPATH": os.pathsep.join(("src", "evals")),
            "HF_HUB_OFFLINE": "1",
            "TRANSFORMERS_OFFLINE": "1",
        }
    )
    try:
        for service, image in IMAGES.items():
            run(["docker", "image", "pull", image])
            evidence["images"][service] = run(
                ["docker", "image", "inspect", "--format", "{{.Id}} {{.RepoDigests}}", image]
            )
        os_name = start(
            "opensearch",
            IMAGES["opensearch"],
            suffix,
            (9200,),
            {
                "discovery.type": "single-node",
                "plugins.security.disabled": "true",
                "DISABLE_INSTALL_DEMO_CONFIG": "true",
                "OPENSEARCH_JAVA_OPTS": "-Xms512m -Xmx512m",
            },
            "2g",
        )
        names.append(os_name)
        os_port = port(os_name, 9200)
        wait_http(os_port, "/", 180)
        with urlopen(f"http://127.0.0.1:{os_port}/", timeout=5) as response:
            os_version = json.load(response).get("version", {}).get("number", "unknown")
        child_env["MEMSPINE_TEST_LIVE_OPENSEARCH_URL"] = f"http://127.0.0.1:{os_port}"
        evidence["services"]["opensearch"] = {
            "version": os_version,
            "port": os_port,
            "bind": "127.0.0.1",
        }

        weaviate_name = start(
            "weaviate",
            IMAGES["weaviate"],
            suffix,
            (8080, 50051),
            {
                "AUTHENTICATION_ANONYMOUS_ACCESS_ENABLED": "true",
                "PERSISTENCE_DATA_PATH": "/var/lib/weaviate",
                "CLUSTER_HOSTNAME": "node1",
                "DEFAULT_VECTORIZER_MODULE": "none",
            },
            "1g",
        )
        names.append(weaviate_name)
        weaviate_port = port(weaviate_name, 8080)
        grpc_port = port(weaviate_name, 50051)
        wait_http(weaviate_port, "/v1/.well-known/ready", 90)
        with urlopen(f"http://127.0.0.1:{weaviate_port}/v1/meta", timeout=5) as response:
            weaviate_version = json.load(response).get("version", "unknown")
        child_env["MEMSPINE_TEST_LIVE_WEAVIATE_URL"] = f"http://127.0.0.1:{weaviate_port}"
        child_env["MEMSPINE_TEST_LIVE_WEAVIATE_GRPC_PORT"] = str(grpc_port)
        evidence["services"]["weaviate"] = {
            "version": weaviate_version,
            "http_port": weaviate_port,
            "grpc_port": grpc_port,
            "bind": "127.0.0.1",
        }

        command = [
            sys.executable,
            "-m",
            "pytest",
            "-p",
            "no:deepeval",
            "-o",
            "addopts=",
            "-q",
            "-rs",
            "--tb=short",
            "tests/integration/providers/test_remote_search_live_contracts.py",
        ]
        result = subprocess.run(
            command,
            cwd=ROOT,
            env=child_env,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            check=False,
        )
        output = redact(
            result.stdout or "",
            [
                child_env["MEMSPINE_TEST_LIVE_OPENSEARCH_URL"],
                child_env["MEMSPINE_TEST_LIVE_WEAVIATE_URL"],
            ],
        )
        print(output, end="" if output.endswith("\n") else "\n")
        evidence["pytest_exit_code"] = result.returncode
        evidence["pytest_summary"] = next(
            (
                line
                for line in reversed(output.splitlines())
                if " passed" in line or " failed" in line
            ),
            "NO SUMMARY",
        )
        if options.report:
            options.report.parent.mkdir(parents=True, exist_ok=True)
            options.report.write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8")
        return result.returncode
    finally:
        for name in reversed(names):
            subprocess.run(
                ["docker", "rm", "--force", name],
                cwd=ROOT,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                check=False,
            )


if __name__ == "__main__":
    raise SystemExit(main())
